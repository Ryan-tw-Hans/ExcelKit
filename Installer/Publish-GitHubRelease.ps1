[CmdletBinding()]
param(
 [Parameter(Mandatory=$true)][string]$Directory,
 [Parameter(Mandatory=$true)][string]$Version
)
$ErrorActionPreference='Stop'
if($Version -notmatch '^(?<file>\d+\.\d+\.\d+\.\d+)-(?<day>\d{8})-(?<seq>\d{2,})$'){throw 'Invalid installer version'}
$day=$Matches.day;$seq=$Matches.seq;$tag='excelkit-package/'+$day+'/'+$seq
$base='ExcelKit-Setup-'+$Version
$folder=[IO.Path]::GetFullPath($Directory)
$exe=Join-Path $folder ($base+'.exe');$manifest=Join-Path $folder ($base+'.manifest.json');$report=Join-Path $folder ($base+'.build.json')
foreach($f in @($exe,$manifest,$report)){if(-not(Test-Path -LiteralPath $f -PathType Leaf)){throw "Missing required file: $f"}}
$build=Get-Content -LiteralPath $report -Raw -Encoding UTF8 | ConvertFrom-Json
$contents=Get-Content -LiteralPath $manifest -Raw -Encoding UTF8 | ConvertFrom-Json
if($build.installer_version -cne $Version -or $contents.installer_version -cne $Version -or $build.release_type -cne 'test' -or $build.source_commit -notmatch '^[0-9a-f]{40}$'){throw 'Invalid version, release type or source commit in report'}
$exeHash=(Get-FileHash -LiteralPath $exe -Algorithm SHA256).Hash
$manifestHash=(Get-FileHash -LiteralPath $manifest -Algorithm SHA256).Hash
if($exeHash -cne ([string]$build.installer_sha256).ToUpperInvariant() -or $manifestHash -cne ([string]$build.manifest_sha256).ToUpperInvariant()){throw 'Build report hash mismatch'}
$ref='refs/tags/'+$tag
$remote=@(& git ls-remote --refs origin $ref 2>$null)
if($LASTEXITCODE -ne 0 -or $remote.Count -ne 1 -or $remote[0] -notmatch ('^'+[regex]::Escape([string]$build.source_commit)+'\s+'+[regex]::Escape($ref)+'$')){throw 'Reservation tag does not match source commit'}
if(-not $env:GH_TOKEN){throw 'GH_TOKEN is required'}
$headers=@{Authorization='Bearer '+$env:GH_TOKEN;Accept='application/vnd.github+json';'User-Agent'='ExcelKit-release';'X-GitHub-Api-Version'='2022-11-28'}
# List authenticated releases, including drafts. A tag lookup alone can miss a draft.
for($page=1;$page -le 100;$page++){
 $response=Invoke-WebRequest -Uri ("https://api.github.com/repos/Ryan-tw-Hans/ExcelKit/releases?per_page=100&page="+$page) -Headers $headers -SkipHttpErrorCheck
 if($response.StatusCode -ne 200){throw "Unable to check existing releases: HTTP $($response.StatusCode)"}
 $existing=@(ConvertFrom-Json -InputObject $response.Content)
 if(@($existing | Where-Object {$_.tag_name -ceq $tag}).Count -ne 0){throw 'Release already exists; inspect it manually, never overwrite'}
 if($existing.Count -lt 100){break}
 if($page -eq 100){throw 'Too many releases to verify safely'}
}
$notes="ExcelKit test installer. This prerelease is not a formal release. Installation, upgrade, COM, GUI and LabVIEW acceptance remain separate.`n`nSource commit: $($build.source_commit)`nInstaller SHA-256: $exeHash`nManifest SHA-256: $manifestHash`n`nDownload the .exe asset to install. Source code archives are generated by GitHub."
& gh release create $tag --repo Ryan-tw-Hans/ExcelKit --verify-tag --draft --prerelease --latest=false --title ("ExcelKit 測試版 "+$Version) --notes $notes
if($LASTEXITCODE -ne 0){throw 'Draft creation failed; inspect GitHub before retry'}
& gh release upload $tag --repo Ryan-tw-Hans/ExcelKit $exe $manifest $report
if($LASTEXITCODE -ne 0){throw 'Asset upload failed; draft retained, inspect GitHub before retry'}
$verifyDir=Join-Path ([IO.Path]::GetTempPath()) ('excelkit-release-verify-'+[Guid]::NewGuid().ToString('N'))
[IO.Directory]::CreateDirectory($verifyDir)|Out-Null
try {
 & gh release download $tag --repo Ryan-tw-Hans/ExcelKit --dir $verifyDir --pattern ($base+'.*')
 if($LASTEXITCODE -ne 0){throw 'Cannot download draft assets for verification'}
 $received=@(Get-ChildItem -LiteralPath $verifyDir -File)
 if($received.Count -ne 3){throw 'Unexpected draft asset count'}
 foreach($file in @($exe,$manifest,$report)){$copy=Join-Path $verifyDir ([IO.Path]::GetFileName($file));if(-not(Test-Path -LiteralPath $copy -PathType Leaf) -or (Get-FileHash -LiteralPath $copy -Algorithm SHA256).Hash -cne (Get-FileHash -LiteralPath $file -Algorithm SHA256).Hash){throw 'Downloaded release asset hash mismatch'}}
} finally {$tempRoot=[IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\')+'\';$safeVerify=[IO.Path]::GetFullPath($verifyDir);if($safeVerify.StartsWith($tempRoot,[StringComparison]::OrdinalIgnoreCase)){Remove-Item -LiteralPath $safeVerify -Recurse -Force -ErrorAction SilentlyContinue}}
& gh release edit $tag --repo Ryan-tw-Hans/ExcelKit --draft=false --prerelease
if($LASTEXITCODE -ne 0){throw 'Release publication failed or result unknown; inspect GitHub before retry'}
Write-Output "Published prerelease $tag; installer SHA-256 $exeHash"
